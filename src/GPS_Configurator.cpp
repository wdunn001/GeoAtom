// Fletcher Algorithm variant used by UBX protocol
void GPSConfigurator::calculateChecksum(const uint8_t *payload, size_t length, uint8_t& ck_a, uint8_t& ck_b) {
    ck_a = 0;
    ck_b = 0;
    // Skip the first two sync bytes (B5 62)
    for (size_t i = 2; i < length - 2; i++) { 
        ck_a = ck_a + payload[i];
        ck_b = ck_b + ck_a;
    }
}


// --- Public Method Implementations ---

bool GPSConfigurator::setBaudRate(uint32_t baud) {
    const uint8_t* command = nullptr;
    size_t length = 0;

    switch (baud) {
        case 4800:
            command = UBX_SET_BAUD_4800;
            length = sizeof(UBX_SET_BAUD_4800);
            break;
        case 9600:
            command = UBX_SET_BAUD_9600;
            length = sizeof(UBX_SET_BAUD_9600);
            break;
        case 19200:
            command = UBX_SET_BAUD_19200;
            length = sizeof(UBX_SET_BAUD_19200);
            break;
        case 38400:
            command = UBX_SET_BAUD_38400;
            length = sizeof(UBX_SET_BAUD_38400);
            break;
        case 57600:
            command = UBX_SET_BAUD_57600;
            length = sizeof(UBX_SET_BAUD_57600);
            break;
        case 115200:
            command = UBX_SET_BAUD_115200;
            length = sizeof(UBX_SET_BAUD_115200);
            break;
        case 921600:
            command = UBX_SET_BAUD_921600;
            length = sizeof(UBX_SET_BAUD_921600);
            break;
        default:
            // Unsupported baud rate
            return false;
    }

    sendUbxCommand(command, length);
    // IMPORTANT: After sending this, the host must immediately change its own baud rate!
    _gps_serial.flush(); // Wait for send to complete
    _gps_serial.updateBaudRate(baud); // Update the HardwareSerial object's baud rate
    return true;
}

