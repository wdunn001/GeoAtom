        case 6: command = UBX_SET_DYNMODEL_AIR_1G; length = sizeof(UBX_SET_DYNMODEL_AIR_1G); break;
        case 7: command = UBX_SET_DYNMODEL_AIR_2G; length = sizeof(UBX_SET_DYNMODEL_AIR_2G); break;
